import { calcBreakEven, calcDrr, calcTurnover } from '@/lib/calculators';

type Field = { key: string; label: string; hint?: string; suffix: string };
type Result = { headline: string; caption: string; good: boolean; rows: [string, string][]; note?: string };
type Spec = {
  title: string;
  lead: string;
  /** Чем ручной расчёт отличается от того же расчёта внутри продукта */
  automation: { title: string; text: string; items: string[] };
  /** Куда логично перейти с результатом этого расчёта */
  next?: { label: string; hint: string; href: string };
  fields: Field[];
  defaults: Record<string, number>;
  compute: (values: Record<string, number>) => Result;
};

const num = (value: number, digits = 0) =>
  value.toLocaleString('ru-RU', { maximumFractionDigits: digits, minimumFractionDigits: 0 });

